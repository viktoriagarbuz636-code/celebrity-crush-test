function isSecretKeyDangerouslyUsed(key) {
  if (!key) return false;
  if (key.startsWith("sb_secret_")) return true;
  if (key.startsWith("eyJ")) {
    try {
      const parts = key.split(".");
      if (parts.length === 3) {
        const payload = JSON.parse(atob(parts[1].replace(/-/g, "+").replace(/_/g, "/")));
        if (payload && payload.role === "service_role") return true;
      }
    } catch (e) {
      // Ignore base64 parse issues
    }
  }
  return false;
}

function isSupabaseConfigured() {
  const urlOk = SUPABASE_URL.startsWith("https://") &&
    !SUPABASE_URL.includes("YOUR_PROJECT_ID") &&
    SUPABASE_URL.includes(".supabase.co");
  const keyTrimmed = (SUPABASE_PUBLISHABLE_KEY || "").trim();
  const keyValidPrefix = keyTrimmed.startsWith("sb_publishable_") || keyTrimmed.startsWith("eyJ");
  const keyOk = keyValidPrefix &&
    !keyTrimmed.includes("REPLACE_ME") &&
    !isSecretKeyDangerouslyUsed(keyTrimmed);
  return urlOk && keyOk;
}

function getSupabaseClient() {
  if (!isSupabaseConfigured()) return null;
  if (!window.supabase || typeof window.supabase.createClient !== "function") return null;
  if (!supabaseClient) {
    supabaseClient = window.supabase.createClient(SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY.trim());
  }
  return supabaseClient;
}

