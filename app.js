function renderQuestion() {
  const question = QUESTIONS[currentQuestionIndex];
  const counter = currentQuestionIndex + 1;
  const progress = Math.round((counter / QUESTIONS.length) * 100);

  byId("question-counter").textContent = `ВОПРОС ${counter} ИЗ ${QUESTIONS.length}`;
  byId("progress-percent").textContent = `${progress}%`;
  byId("progress-bar").style.width = `${progress}%`;
  byId("progress-track").setAttribute("aria-valuemax", String(QUESTIONS.length));
  byId("progress-track").setAttribute("aria-valuenow", String(counter));
  byId("question-title").textContent = question.title;

  const optionBox = byId("answer-options");
  optionBox.replaceChildren();

  question.options.forEach(([label, category]) => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "option-button";
    button.textContent = label;
    button.setAttribute("aria-pressed", String(answers[currentQuestionIndex] === category));
    button.addEventListener("click", () => {
      answers[currentQuestionIndex] = category;
      optionBox.querySelectorAll(".option-button").forEach((item) => {
        item.setAttribute("aria-pressed", String(item === button));
      });
      byId("next-button").disabled = false;
    });
    optionBox.appendChild(button);
  });

  byId("back-button").disabled = currentQuestionIndex === 0;
  byId("next-button").disabled = !answers[currentQuestionIndex];
  byId("next-button").textContent = currentQuestionIndex === QUESTIONS.length - 1
    ? "Узнать результат 💗"
    : "Дальше →";
}

function goBack() {
  if (currentQuestionIndex === 0) return;
  currentQuestionIndex -= 1;
  renderQuestion();
}

function goNext() {
  if (!answers[currentQuestionIndex]) return;
  if (currentQuestionIndex < QUESTIONS.length - 1) {
    currentQuestionIndex += 1;
    renderQuestion();
    return;
  }
  calculateAndShowResult();
}

function renderBreakdownAndRunnersUp(scores, chosenPerson, candidatePool) {
  const breakdownEl = byId("result-breakdown");
  if (breakdownEl) {
    breakdownEl.replaceChildren();
    const sortedCats = Object.keys(CATEGORY_LABELS)
      .filter((c) => c !== "secret")
      .map((cat) => [cat, scores[cat] || 0])
      .filter(([, count]) => count > 0)
      .sort((a, b) => b[1] - a[1]);

    sortedCats.forEach(([cat, count]) => {
      const pct = Math.round((count / QUESTIONS.length) * 100);
      const row = document.createElement("div");
      row.className = "breakdown-row";
      const label = document.createElement("span");
      label.textContent = CATEGORY_LABELS[cat] || cat;
      const val = document.createElement("strong");
      val.textContent = `${pct}%`;
      const barWrap = document.createElement("div");
      barWrap.className = "breakdown-bar-wrap";
      const barFill = document.createElement("div");
      barFill.className = "breakdown-bar-fill";
      barFill.style.width = `${pct}%`;
      barWrap.appendChild(barFill);
      row.append(label, val, barWrap);
      breakdownEl.appendChild(row);
    });
  }

  const runnersEl = byId("result-runners-up");
  if (runnersEl) {
    runnersEl.replaceChildren();
    const others = candidatePool.filter((p) => p.id !== chosenPerson.id && p.type !== "secret");
    const shuffled = others.slice().sort(() => Math.random() - 0.5).slice(0, 3);
    shuffled.forEach((p) => {
      const li = document.createElement("li");
      const emojiSpan = document.createElement("span");
      emojiSpan.textContent = p.emoji || "✨";
      const textWrap = document.createElement("div");
      textWrap.appendChild(document.createTextNode(p.name));
      const sub = document.createElement("span");
      sub.className = "runner-sub";
      sub.textContent = p.subtitle;
      textWrap.appendChild(sub);
      li.append(emojiSpan, textWrap);
      runnersEl.appendChild(li);
    });
  }
}

function calculateAndShowResult() {
  const scores = {};
  answers.forEach((category) => {
    scores[category] = (scores[category] || 0) + 1;
  });

  const highestScore = Math.max(...Object.values(scores));
  const winningCategories = Object.keys(scores).filter((category) => scores[category] === highestScore);
  const winningCategory = winningCategories[Math.floor(Math.random() * winningCategories.length)];
  const shouldUseSecretResult = Math.random() < 0.05;

  const filteredByGroup = PEOPLE.filter((person) => person.type !== "secret" && activeGroups.includes(person.group));
  const basePool = filteredByGroup.length > 0 ? filteredByGroup : PEOPLE.filter((person) => person.type !== "secret");

  let pool = shouldUseSecretResult
    ? PEOPLE.filter((person) => person.type === "secret")
    : basePool.filter((person) => person.type === winningCategory);

  if (pool.length === 0) pool = basePool;
  currentResult = pool[Math.floor(Math.random() * pool.length)];

  byId("quiz-screen").hidden = true;
  byId("result-screen").hidden = false;

  const emojiEl = byId("result-emoji");
  if (emojiEl) emojiEl.textContent = currentResult.emoji || "💘";

  const catBadge = byId("result-category-badge");
  if (catBadge) catBadge.textContent = CATEGORY_LABELS[currentResult.type] || "Твой типаж";

  const grpBadge = byId("result-group-badge");
  if (grpBadge) {
    grpBadge.textContent = currentResult.isRussian && currentResult.group === "football"
      ? "🇷🇺⚽ Российский футболист"
      : (GROUP_LABELS[currentResult.group] || "✨ Кандидат");
  }

  byId("result-name").textContent = currentResult.name;
  byId("result-subtitle").textContent = currentResult.subtitle;
  byId("result-description").textContent = currentResult.description;
  byId("result-verdict").textContent = currentResult.verdict;

  renderBreakdownAndRunnersUp(scores, currentResult, basePool);

  byId("save-form").hidden = false;
  byId("save-success").hidden = true;
  byId("save-button").disabled = false;
  byId("display-name").value = preEnteredName || "";
  setStatus(byId("save-status"), "");

  if (isSecretKeyDangerouslyUsed(SUPABASE_PUBLISHABLE_KEY)) {
    setStatus(byId("save-status"), "Внимание: в app.js вставлен секретный ключ вместо публичного! Замени его на publishable / anon key.", true);
    return;
  }

  if (preEnteredName && shouldAutoPublish) {
    submitResultToBoard(preEnteredName, true);
  }
}

function normalizeDisplayName(value) {
  const cleaned = String(value || "")
    .normalize("NFC")
    .replace(/[\u0000-\u001F\u007F]/g, "")
    .replace(/\s+/g, " ")
    .trim();
  return Array.from(cleaned).slice(0, 24).join("");
}

function createUuidV4() {
  const bytes = new Uint8Array(16);
  if (window.crypto && typeof window.crypto.getRandomValues === "function") {
    window.crypto.getRandomValues(bytes);
  } else {
    for (let i = 0; i < 16; i += 1) bytes[i] = Math.floor(Math.random() * 256);
  }
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

function getPendingSubmission(displayName, resultKey) {
  const storageKey = "celebrityQuizPendingSubmission";
  try {
    const saved = localStorage.getItem(storageKey);
    if (saved) {
      const pending = JSON.parse(saved);
      if (pending && pending.displayName === displayName && pending.resultKey === resultKey && pending.id) {
        return pending;
      }
    }
  } catch (error) {
    // localStorage may be disabled
  }

  const pending = {
    id: createUuidV4(),
    displayName,
    resultKey
  };
  try {
    localStorage.setItem(storageKey, JSON.stringify(pending));
  } catch (error) {
    // Ignore
  }
  return pending;
}

function clearPendingSubmission(submissionId) {
  try {
    const storageKey = "celebrityQuizPendingSubmission";
    const saved = localStorage.getItem(storageKey);
    if (!saved) return;
    const pending = JSON.parse(saved);
    if (pending && pending.id === submissionId) localStorage.removeItem(storageKey);
  } catch (error) {
    // Ignore
  }
}

async function submitResultToBoard(rawName, isAuto = false) {
  if (!currentResult) return;
  const nameInput = byId("display-name");
  const displayName = normalizeDisplayName(rawName);
  if (nameInput) nameInput.value = displayName;

  if (!displayName) {
    if (nameInput && !isAuto) {
      nameInput.setCustomValidity("Введи имя или ник.");
      nameInput.reportValidity();
    }
    return;
  }
  if (nameInput) nameInput.setCustomValidity("");

  const saveButton = byId("save-button");
  if (saveButton) saveButton.disabled = true;
  setStatus(byId("save-status"), isAuto ? "Автоматически публикуем твой результат на доске…" : "Сохраняем результат…");

  const pending = getPendingSubmission(displayName, currentResult.id);
  const client = getSupabaseClient();

  if (!client) {
    // Local Demo Mode fallback
    saveLocalBoardRow(pending.id, displayName, currentResult.id);
    clearPendingSubmission(pending.id);
    byId("save-form").hidden = true;
    byId("save-success").hidden = false;
    const successText = byId("save-success-text");
    if (successText) {
      successText.textContent = isAuto
        ? `Результат (${displayName} — ${currentResult.name}) автоматически добавлен на демо-доску ✨`
        : "Готово! Твой результат добавлен на демо-доску ✨";
    }
    setStatus(byId("save-status"), "");
    if (typeof reloadBoardFn === "function") reloadBoardFn(true);
    return;
  }

  try {
    const { error } = await client.from(TABLE_NAME).insert({
      submission_id: pending.id,
      display_name: displayName,
      result_key: currentResult.id
    });

    if (error && error.code !== "23505") throw error;

    clearPendingSubmission(pending.id);
    byId("save-form").hidden = true;
    byId("save-success").hidden = false;
    const successText = byId("save-success-text");
    if (successText) {
      successText.textContent = isAuto
        ? `Результат (${displayName} — ${currentResult.name}) автоматически опубликован на общей доске ✨`
        : "Готово! Твой результат появился на общей доске ✨";
    }
    setStatus(byId("save-status"), error ? "Этот результат уже был сохранён." : "");
    if (typeof reloadBoardFn === "function") reloadBoardFn(true);
  } catch (error) {
    console.error("Could not save quiz result:", error);
    setStatus(byId("save-status"), "Не удалось отправить в облако Supabase. Проверь интернет или выполни обновлённый supabase.sql.", true);
    if (saveButton) saveButton.disabled = false;
  }
}

