function initUnifiedNavigation() {
  const quizView = byId("quiz-page-view");
  const resultsView = byId("results-page-view");
  const toResultsBtns = document.querySelectorAll("[data-nav-target='results']");
  const toQuizBtns = document.querySelectorAll("[data-nav-target='quiz']");

  if (!quizView || !resultsView) return;

  function showView(target) {
    const isResults = target === "results";
    quizView.hidden = isResults;
    resultsView.hidden = !isResults;
    if (isResults && typeof reloadBoardFn === "function") {
      reloadBoardFn(true, true);
    }
    window.scrollTo({ top: 0, behavior: "smooth" });
  }

  toResultsBtns.forEach((btn) => btn.addEventListener("click", () => showView("results")));
  toQuizBtns.forEach((btn) => btn.addEventListener("click", () => showView("quiz")));
}

function initApp() {
  const page = document.body.dataset.page;
  if (page === "quiz") initQuizPage();
  if (page === "results") initResultsPage();
  if (page === "unified") {
    initQuizPage();
    initResultsPage();
    initUnifiedNavigation();
  }
}

document.addEventListener("DOMContentLoaded", initApp);
