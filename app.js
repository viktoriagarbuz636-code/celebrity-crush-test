function formatDate(value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "Только что";
  return new Intl.DateTimeFormat("ru-RU", {
    day: "2-digit",
    month: "short",
    hour: "2-digit",
    minute: "2-digit"
  }).format(date);
}

function updatePartyStats(rows, totalCount) {
  const statTotal = byId("stat-total");
  const statVibe = byId("stat-top-vibe");
  const statCrush = byId("stat-top-crush");
  if (!statTotal || !statVibe || !statCrush) return;

  const total = totalCount !== null && totalCount !== undefined ? totalCount : rows.length;
  statTotal.textContent = String(total);

  if (!rows || rows.length === 0) {
    statVibe.textContent = "Ждём первых ✨";
    statCrush.textContent = "Пока секрет 💌";
    return;
  }

  const vibeCounts = {};
  const crushCounts = {};

  rows.forEach((row) => {
    const person = PEOPLE_BY_ID[row.result_key];
    if (!person) return;
    vibeCounts[person.type] = (vibeCounts[person.type] || 0) + 1;
    crushCounts[person.name] = (crushCounts[person.name] || 0) + 1;
  });

  const topVibeEntry = Object.entries(vibeCounts).sort((a, b) => b[1] - a[1])[0];
  const topCrushEntry = Object.entries(crushCounts).sort((a, b) => b[1] - a[1])[0];

  statVibe.textContent = topVibeEntry ? (CATEGORY_LABELS[topVibeEntry[0]] || topVibeEntry[0]) : "—";
  statCrush.textContent = topCrushEntry ? `${topCrushEntry[0]} (${topCrushEntry[1]})` : "—";
}

function createResultCard(row, index) {
  const person = PEOPLE_BY_ID[row.result_key];
  const card = document.createElement("article");
  card.className = "result-card";

  const number = document.createElement("div");
  number.className = "result-number";
  number.textContent = person && person.emoji ? person.emoji : String(index + 1);

  const content = document.createElement("div");
  const header = document.createElement("div");
  header.className = "result-card-header";

  const name = document.createElement("h2");
  name.textContent = `${index + 1}. ${row.display_name || "Без имени"}`;

  const badge = document.createElement("span");
  badge.className = "category-badge";
  badge.textContent = person ? (CATEGORY_LABELS[person.type] || "Совпадение") : "Архив";

  header.append(name, badge);

  const match = document.createElement("p");
  match.className = "matched-name";
  match.textContent = person ? `💘 ${person.name}` : "Результат из старой версии теста";

  const subtitle = document.createElement("p");
  subtitle.textContent = person ? `${person.subtitle} — ${person.verdict}` : "";

  const time = document.createElement("time");
  time.dateTime = row.created_at || "";
  time.textContent = formatDate(row.created_at);

  content.append(header, match);
  if (subtitle.textContent) content.appendChild(subtitle);
  content.appendChild(time);
  card.append(number, content);
  return card;
}

function initResultsPage() {
  const client = getSupabaseClient();
  const list = byId("results-list");
  const count = byId("results-count");
  const status = byId("results-status");
  const refreshButton = byId("refresh-button");
  const loadMoreButton = byId("load-more-button");
  const autoRefreshButton = byId("auto-refresh-button");
  const autoRefreshLabel = byId("auto-refresh-label");
  const shareButton = byId("share-board-button");
  const qrDrawer = byId("qr-drawer");
  const shareUrlInput = byId("share-url-input");
  const copyUrlButton = byId("copy-url-button");
  const clearDemoButton = byId("clear-demo-button");
  const demoBannerResults = byId("demo-mode-banner-results");

  if (!list || !count || !refreshButton || !loadMoreButton) return;

  let offset = 0;
  let loadedCount = 0;
  let totalCount = null;
  let isLoading = false;
  let allLoadedRows = [];
  let autoRefreshEnabled = true;
  let pollTimer = null;

  if (!client && demoBannerResults) {
    demoBannerResults.hidden = false;
  }
  if (!client && clearDemoButton) {
    clearDemoButton.hidden = false;
    clearDemoButton.addEventListener("click", () => {
      clearLocalBoardRows();
      loadResults(true, true);
    });
  }

  if (shareButton && qrDrawer && shareUrlInput) {
    const quizUrl = window.location.href.replace(/results\.html.*$/, "index.html");
    shareUrlInput.value = quizUrl;
    shareButton.addEventListener("click", () => {
      qrDrawer.hidden = !qrDrawer.hidden;
    });
  }

  if (copyUrlButton && shareUrlInput) {
    copyUrlButton.addEventListener("click", () => {
      shareUrlInput.select();
      try {
        if (navigator.clipboard && navigator.clipboard.writeText) {
          navigator.clipboard.writeText(shareUrlInput.value);
        } else {
          document.execCommand("copy");
        }
        copyUrlButton.textContent = "Скопировано! ✓";
        setTimeout(() => {
          copyUrlButton.textContent = "Скопировать ссылку";
        }, 2000);
      } catch (e) {
        document.execCommand("copy");
      }
    });
  }

  async function loadResults(reset = false, silent = false) {
    if (isLoading) return;
    isLoading = true;
    if (!silent) {
      refreshButton.disabled = true;
      loadMoreButton.disabled = true;
      setStatus(status, reset ? "Обновляем список…" : "Загружаем следующие результаты…");
    }

    if (!client) {
      const localRows = getLocalBoardRows();
      list.replaceChildren();
      loadedCount = 0;
      localRows.forEach((row) => list.appendChild(createResultCard(row, loadedCount++)));
      count.textContent = `Всего на доске (демо): ${localRows.length}`;
      updatePartyStats(localRows, localRows.length);
      if (localRows.length === 0) {
        const empty = document.createElement("div");
        empty.className = "empty-state";
        empty.textContent = "На доске пока пусто. Пройди тест первой и опубликуй результат! 💗";
        list.appendChild(empty);
      }
      loadMoreButton.hidden = true;
      setStatus(status, silent ? "" : "Демо-список актуален.");
      isLoading = false;
      refreshButton.disabled = false;
      loadMoreButton.disabled = false;
      return;
    }

    if (reset) {
      offset = 0;
      loadedCount = 0;
      totalCount = null;
      allLoadedRows = [];
    }

    try {
      const start = offset;
      const end = offset + PAGE_SIZE - 1;
      const { data, error, count: exactCount } = await client
        .from(TABLE_NAME)
        .select("id, display_name, result_key, created_at", { count: "exact" })
        .order("created_at", { ascending: false })
        .order("id", { ascending: false })
        .range(start, end);

      if (error) throw error;

      totalCount = exactCount;
      const rows = data || [];
      if (reset) list.replaceChildren();

      rows.forEach((row) => {
        allLoadedRows.push(row);
        list.appendChild(createResultCard(row, loadedCount++));
      });
      offset += rows.length;

      const totalText = totalCount === null ? loadedCount : totalCount;
      count.textContent = `Всего прошли: ${totalText}`;
      updatePartyStats(allLoadedRows, totalText);

      if (loadedCount === 0) {
        const empty = document.createElement("div");
        empty.className = "empty-state";
        empty.textContent = "Пока никто не прошёл тест. Будь первой! 💗";
        list.appendChild(empty);
      }

      loadMoreButton.hidden = !(totalCount !== null && offset < totalCount);
      if (!silent) {
        setStatus(status, rows.length > 0 ? "Список актуален ✨" : "");
      }
    } catch (error) {
      console.error("Could not load quiz results:", error);
      setStatus(status, "Не удалось загрузить результаты из Supabase. Проверь интернет и выполнение supabase.sql.", true);
      count.textContent = loadedCount ? `Загружено: ${loadedCount}` : "Ошибка подключения";
    } finally {
      isLoading = false;
      refreshButton.disabled = false;
      loadMoreButton.disabled = false;
    }
  }

  reloadBoardFn = loadResults;

  function startAutoRefresh() {
    if (pollTimer) clearInterval(pollTimer);
    pollTimer = setInterval(() => {
      if (autoRefreshEnabled && !document.hidden && offset <= PAGE_SIZE) {
        loadResults(true, true);
      }
    }, AUTO_REFRESH_INTERVAL_MS);
  }

  if (autoRefreshButton && autoRefreshLabel) {
    autoRefreshButton.addEventListener("click", () => {
      autoRefreshEnabled = !autoRefreshEnabled;
      autoRefreshButton.setAttribute("aria-pressed", String(autoRefreshEnabled));
      autoRefreshLabel.textContent = autoRefreshEnabled ? "Live-обновление: ВКЛ" : "Live-обновление: ВЫКЛ";
    });
  }

  if (client && typeof client.channel === "function") {
    try {
      client
        .channel("public-quiz-results-live")
        .on(
          "postgres_changes",
          { event: "INSERT", schema: "public", table: TABLE_NAME },
          () => {
            if (autoRefreshEnabled) loadResults(true, true);
          }
        )
        .subscribe();
    } catch (e) {
      // Fallback polling still handles updates
    }
  }

  refreshButton.addEventListener("click", () => loadResults(true, false));
  loadMoreButton.addEventListener("click", () => loadResults(false, false));
  startAutoRefresh();
  loadResults(true, false);
}

